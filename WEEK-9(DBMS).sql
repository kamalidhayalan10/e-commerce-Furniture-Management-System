USE FURNITURE;

SELECT COUNT(*) AS TOTAL_PRODUCTS
FROM PRODUCT;

SELECT SUM(TOTAL_PRICE) AS TOTAL_SALES
FROM ORDERSTABLE;

SELECT AVG(TOTAL_PRICE) AS AVERAGE_SALES
FROM ORDERSTABLE;

SELECT
MIN(TOTAL_PRICE) AS MINIMUM_SALES,
MAX(TOTAL_PRICE) AS MAXIMUM_SALES
FROM ORDERSTABLE;

SELECT
ORDER_ID,
CUSTOMER_NAME,
TOTAL_PRICE,
ORDER_STATUS
FROM ORDERSTABLE;

SELECT
CUSTOMER_NAME,
SUM(TOTAL_PRICE) AS PURCHASE_AMOUNT
FROM ORDERSTABLE
GROUP BY CUSTOMER_NAME
ORDER BY PURCHASE_AMOUNT DESC
LIMIT 5;

SELECT
PRODUCT.PRODUCTID,
PRODUCT.PRODUCTNAME,
SUM(ORDERSDETAIL.PRODUCT_QUANTITY) AS TOTAL_SOLD
FROM PRODUCT
JOIN ORDERSDETAIL
ON PRODUCT.PRODUCTID = ORDERSDETAIL.PRODUCTID
GROUP BY PRODUCT.PRODUCTID, PRODUCT.PRODUCTNAME
ORDER BY TOTAL_SOLD DESC;

SELECT
CATEGORY.CATEGORYNAME,
SUM(ORDERSDETAIL.PRODUCT_QUANTITY) AS TOTAL_QUANTITY,
SUM(ORDERSDETAIL.PRODUCT_QUANTITY * ORDERSDETAIL.UNIT_PRICE) AS TOTAL_SALES
FROM CATEGORY
JOIN PRODUCT
ON CATEGORY.CATEGORYID = PRODUCT.CATEGORYID
JOIN ORDERSDETAIL
ON PRODUCT.PRODUCTID = ORDERSDETAIL.PRODUCTID
GROUP BY CATEGORY.CATEGORYID, CATEGORY.CATEGORYNAME
ORDER BY TOTAL_SALES DESC;

SELECT
SUM(PRODUCT_QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM ORDERSDETAIL;


SELECT
PRODUCT.PRODUCTID,
PRODUCT.PRODUCTNAME,
SUM(ORDERSDETAIL.PRODUCT_QUANTITY * ORDERSDETAIL.UNIT_PRICE) AS SALES_AMOUNT
FROM PRODUCT
JOIN ORDERSDETAIL
ON PRODUCT.PRODUCTID = ORDERSDETAIL.PRODUCTID
GROUP BY PRODUCT.PRODUCTID, PRODUCT.PRODUCTNAME
ORDER BY SALES_AMOUNT DESC;