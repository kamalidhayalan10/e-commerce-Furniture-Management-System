USE FURNITURE;


SELECT ORDERSTABLE.ORDER_ID,
    ORDERSDETAIL.PRODUCTID,
    ORDERSDETAIL.PRODUCT_QUANTITY
FROM ORDERSTABLE
INNER JOIN ORDERSDETAIL
ON ORDERSTABLE.ORDER_ID = ORDERSDETAIL.ORDER_ID;


SELECT ORDERSTABLE.ORDER_ID,
    ORDERSDETAIL.PRODUCTID,
    ORDERSDETAIL.PRODUCT_QUANTITY
FROM ORDERSTABLE
LEFT JOIN ORDERSDETAIL
ON ORDERSTABLE.ORDER_ID = ORDERSDETAIL.ORDER_ID;


SELECT ORDERSTABLE.ORDER_ID,
    ORDERSTABLE.CUSTOMER_NAME,
    ORDERSDETAIL.PRODUCTID,
    ORDERSDETAIL.PRODUCT_QUANTITY
FROM ORDERSTABLE
RIGHT JOIN ORDERSDETAIL
ON ORDERSTABLE.ORDER_ID = ORDERSDETAIL.ORDER_ID;


SELECT ORDERSTABLE.ORDER_ID,
    ORDERSTABLE.TOTAL_PRICE,
    PAYMENT.PAYMENT_MODE,
    PAYMENT.PAYMENT_AMOUNT
FROM ORDERSTABLE
INNER JOIN PAYMENT
ON ORDERSTABLE.ORDER_ID = PAYMENT.ORDER_ID;

SELECT PRODUCT.PRODUCTNAME,
    CATEGORY.CATEGORYNAME
FROM PRODUCT
INNER JOIN CATEGORY
ON PRODUCT.CATEGORYID = CATEGORY.CATEGORYID;


SELECT ORDERSTABLE.ORDER_ID,
    ORDERSTABLE.CUSTOMER_NAME,
    PAYMENT.PAYMENT_MODE,
    PAYMENT.PAYMENT_STATUS
FROM ORDERSTABLE
INNER JOIN PAYMENT
ON ORDERSTABLE.ORDER_ID = PAYMENT.ORDER_ID;


SELECT ORDERSTABLE.ORDER_ID,
    PRODUCT.PRODUCTNAME,
    ORDERSDETAIL.PRODUCT_QUANTITY,
    PAYMENT.PAYMENT_STATUS
FROM ORDERSTABLE
INNER JOIN ORDERSDETAIL
ON ORDERSTABLE.ORDER_ID = ORDERSDETAIL.ORDER_ID
INNER JOIN PRODUCT
ON ORDERSDETAIL.PRODUCTID = PRODUCT.PRODUCTID
LEFT JOIN PAYMENT
ON ORDERSTABLE.ORDER_ID = PAYMENT.ORDER_ID;