USE FURNITURE;

CREATE TABLE SELLER
(
    SELLERID INT PRIMARY KEY,
    SELLERNAME VARCHAR(50),
    CONTACT VARCHAR(10),
    EMAILID VARCHAR(100)
);

CREATE TABLE INVENTORY
(
    INVENTORYID INT PRIMARY KEY,
    SELLERID INT,
    PRODUCTID INT,
    STOCK_QUANTITY INT,
    STATUS VARCHAR(20),
    
    FOREIGN KEY (SELLERID)
    REFERENCES SELLER(SELLERID),
    
    FOREIGN KEY (PRODUCTID)
    REFERENCES PRODUCT(PRODUCTID)
);

