USE FURNITURE;

CREATE TABLE REVIEW
(
    REVIEW_ID INT PRIMARY KEY,
    CUSTOMER_NAME VARCHAR(50),
    PRODUCTID INT,
    REVIEW_TEXT VARCHAR(100),
    REVIEW_DATE DATE,
    FOREIGN KEY(PRODUCTID)
    REFERENCES PRODUCT(PRODUCTID)
);

CREATE TABLE RATING
(
    RATING_ID INT PRIMARY KEY,
    REVIEW_ID INT,
    RATING INT,
    FOREIGN KEY(REVIEW_ID)
    REFERENCES REVIEW(REVIEW_ID)
);

