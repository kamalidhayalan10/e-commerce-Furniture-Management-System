USE FURNITURE;

CREATE TABLE PAYMENT
(
    PAYMENT_ID INT PRIMARY KEY,
    ORDER_ID INT,
    PAYMENT_MODE VARCHAR(20),
    PAYMENT_DATE DATE,
    PAYMENT_AMOUNT DECIMAL(10,2),
    PAYMENT_STATUS VARCHAR(20),
    
    FOREIGN KEY(ORDER_ID)
    REFERENCES ORDERSTABLE(ORDER_ID)
);

